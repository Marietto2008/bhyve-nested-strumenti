#!/usr/bin/env python3
# Claude 24/10/2026 -- parere #44 §8: analisi della prova A/B/A x2APIC (run-x2apic.sh), solo
# contatori nativi. Per ogni avvio (A1, B, A2) e intervallo (C0 = Windows senza WSL, prova =
# parte misurata della prova ext4): frequenze per secondo dei contatori di bhyvectl --get-stats
# (somma dei 2 vCPU), quota di L0 dal TSC, tratti a interrupt disabilitati; dalla prova, buchi e
# durata media dei passi del ciclo dd/sha/rilettura.
# uso: x2_an.py <cartella della corsa>
import re, sys, statistics as st
from collections import defaultdict
d = sys.argv[1]
TSC = 3600018355
foto = {}; cur = None; vc = None
for l in open(f"{d}/foto.txt", errors="replace"):
    m = re.match(r"FOTO (\S+) ([\d.]+)", l)
    if m: cur = m.group(1); foto[cur] = {"t": float(m.group(2)), "s": defaultdict(int), "cpu": 0.0}; vc = None; continue
    if cur is None: continue
    m = re.match(r"hw\.vmm\.vmx\.(\S+): (\d+)", l)
    if m: foto[cur]["s"]["sysctl:" + m.group(1)] = int(m.group(2)); continue
    m = re.match(r"\s*\d+\s+(\d+):([\d.]+)\s+bhyve/vcpu (\d+)", l)
    if m: foto[cur]["cpu"] += int(m.group(1)) * 60 + float(m.group(2)); continue
    m = re.match(r"(.+?)\s{2,}|\t", l)
    m = re.match(r"(.*\S)\s+(\d+)$", l.rstrip("\n"))
    if m and not re.match(r"vcpu\d+ stats", l):
        foto[cur]["s"][m.group(1).strip()] += int(m.group(2))
K = [("total number of vm exits", "uscite totali"),
     ("vm exits for instruction emulation", "emulazione istruzioni (MMIO)"),
     ("number of times rdmsr was intercepted", "RDMSR"),
     ("number of times wrmsr was intercepted", "WRMSR"),
     ("vm exits due to external interrupt", "interrupt esterni"),
     ("vm exits due to interrupt window opening", "finestre interrupt"),
     ("number of times hlt was intercepted", "HLT"),
     ("number of times in/out was intercepted", "IN/OUT"),
     ("number of vm exits handled in userspace", "uscite in userland"),
     ("ingressi in L2", "ingressi in L2"),
     ("exit nested gestite nello slow path", "slow path nested"),
     ("ipis sent from vcpu", "IPI inviati"),
     ("timer interrupts generated by vlapic", "interrupt timer vlapic"),
     ("vcpu migration across host cpus", "\"migrazioni\" (lastcpu)"),
     ("Number of vpid invalidations done", "INVVPID fatte"),
     ("INVEPT single-context dell'L1", "INVEPT dell'L1")]
def diff(a, b):
    A, B = foto[a], foto[b]; dt = B["t"] - A["t"]
    r = {k: (B["s"][k] - A["s"][k]) / dt for k, _ in K}
    cpu = B["cpu"] - A["cpu"]
    g = (B["s"]["sysctl:nested_l1_tsc"] + B["s"]["sysctl:nested_l2_tsc"] - A["s"]["sysctl:nested_l1_tsc"] - A["s"]["sysctl:nested_l2_tsc"]) / TSC
    r["_L0"] = 100 * (1 - g / cpu) if cpu > 0 else float("nan")
    r["_cpu"] = cpu / dt
    for t in ("exit_l1", "ent_l1", "exit_l2", "ent_l2"):
        c = B["s"][f"sysctl:vst_t_{t}"] - A["s"][f"sysctl:vst_t_{t}"]
        r["_" + t] = 100 * c / TSC / cpu if cpu > 0 else float("nan")
    return r, dt
fasi = [F for F in ("A1", "B", "A2") if f"{F}-C0-inizio" in foto]
cfg = {}
for l in open(f"{d}/configurazioni.txt"):
    p = l.split()
    if len(p) == 2: cfg[p[0]] = p[1]
for inter, (a, b) in (("C0 (Windows senza WSL)", ("C0-inizio", "C0-fine")), ("prova ext4", ("prova-inizio", "prova-fine"))):
    R = {}
    for F in fasi:
        if f"{F}-{a}" in foto and f"{F}-{b}" in foto: R[F] = diff(f"{F}-{a}", f"{F}-{b}")
    print(f"\n######## {inter}  (al secondo, somma dei 2 vCPU)")
    print(f"  {'contatore':<32}" + "".join(f"{F + (' x2APIC' if 'x2apic' in cfg.get(F,'') else ''):>14}" for F in R))
    for k, nome in K:
        print(f"  {nome:<32}" + "".join(f"{R[F][0][k]:14.0f}" for F in R))
    print(f"  {'quota L0 (TSC) %':<32}" + "".join(f"{R[F][0]['_L0']:14.1f}" for F in R))
    print(f"  {'CPU dei thread vCPU (s/s)':<32}" + "".join(f"{R[F][0]['_cpu']:14.2f}" for F in R))
    for t in ("exit_l1", "ent_l1", "exit_l2", "ent_l2"):
        print(f"  {'tratto ' + t + ' % CPU':<32}" + "".join(f"{R[F][0]['_' + t]:14.1f}" for F in R))
    print(f"  {'durata s':<32}" + "".join(f"{R[F][1]:14.0f}" for F in R))
# prova: buchi e passi
print("\n######## prova ext4: buchi e passi del ciclo (solo parte misurata)")
for F in fasi:
    try:
        o = []
        for l in open(f"{d}/gapmem-gapmon-{F}.txt"):
            if l.startswith("SYNC"):
                p = list(map(int, l.split()[1:]))
                if p[1] - p[0] < 5e6: o.append(p[3] - (p[0] + p[1]) / 2)
        G = [int(m.group(1)) for m in (re.match(r"BUCO (\d+) ms", l) for l in open(f"{d}/gapmem-gapmon-{F}.txt")) if m]
        ev = [(m.group(1), m.group(2), float(m.group(3))) for m in (re.match(r"CICLO (\S+) (\S+) ([\d.]+)", l) for l in open(f"{d}/gapmem-{F}.log")) if m]
    except FileNotFoundError:
        continue
    du = defaultdict(list); nc = 0
    for i in range(len(ev) - 1):
        c, p, t = ev[i]
        if c.startswith("R") or ev[i + 1][0] != c: continue
        du[p].append(ev[i + 1][2] - t)
        nc += p == "dd"
    print(f"  {F:<3} {cfg.get(F,''):<40} cicli {nc:2d}  buchi {len(G):3d} (somma {sum(G)/1000:5.1f} s, mediana {st.median(G) if G else 0:5.0f} ms)  "
          + "  ".join(f"{p} {st.mean(du[p]):5.1f} s" for p in ("dd", "sha", "rilettura") if du[p]))
